# Local development install: plain `python -m venv` + `pip install -e`, no uv.
#
# install.sh / install.ps1 are the end-user Studio installer -- they lean on uv
# for managed Python downloads and CUDA/ROCm/CPU torch-backend detection, which
# is the right tradeoff for someone with no dev environment yet. This script is
# for the opposite case: a developer who already has a matching `python3` on
# PATH and wants an editable checkout with nothing beyond pip involved. It does
# not download or manage Python itself -- point --python at whichever
# interpreter you want (3.14 by default; anything satisfying pyproject's
# requires-python works).
#
# On Linux/WSL x86_64 and aarch64, plain `pip install torch` already resolves a
# CUDA-enabled wheel (the nvidia-* packages ride along as normal deps) -- no
# --torch-backend flag needed. Windows and macOS need a different route: see
# README.md's Advanced Installation section for the extras/index this project
# defines for those (windows, cu*only* extras).
#
# Usage:
#   scripts/dev_install.sh [--python PATH] [--venv DIR] [--extras LIST] [--lock] [--no-editable]
#
# Options:
#   --python PATH   Interpreter to build the venv from (default: python3.14,
#                    falling back to python3 if that is already 3.14+).
#   --venv DIR       Venv location (default: <repo root>/.venv).
#   --extras LIST    Comma-separated pyproject extras (default: huggingface,studio).
#                    Pass an empty string for the bare package with no extras.
#   --lock           After installing, freeze exact resolved versions to
#                    requirements/dev-<python tag>.lock.txt for reproducibility.
#   --no-editable    Install the package normally instead of `pip install -e`.

set -eu

_usage() {
    sed -n '/^# Usage:/,/^set -eu/p' "$0" | sed '$d; s/^# \{0,1\}//'
}

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"

PYTHON_BIN=""
VENV_DIR="$REPO_ROOT/.venv"
EXTRAS="huggingface,studio"
DO_LOCK=false
EDITABLE=true

while [ $# -gt 0 ]; do
    case "$1" in
        --python) PYTHON_BIN="$2"; shift 2 ;;
        --venv) VENV_DIR="$2"; shift 2 ;;
        --extras) EXTRAS="$2"; shift 2 ;;
        --lock) DO_LOCK=true; shift ;;
        --no-editable) EDITABLE=false; shift ;;
        -h|--help) _usage; exit 0 ;;
        *) echo "unknown argument: $1" >&2; _usage >&2; exit 1 ;;
    esac
done

# ── Resolve the interpreter ──
if [ -z "$PYTHON_BIN" ]; then
    if command -v python3.14 >/dev/null 2>&1; then
        PYTHON_BIN="python3.14"
    elif command -v python3 >/dev/null 2>&1; then
        PYTHON_BIN="python3"
    else
        echo "ERROR: no python3.14 or python3 found on PATH." >&2
        echo "Install Python 3.14 first, or pass --python /path/to/python3.14." >&2
        exit 1
    fi
fi

if ! command -v "$PYTHON_BIN" >/dev/null 2>&1 && [ ! -x "$PYTHON_BIN" ]; then
    echo "ERROR: '$PYTHON_BIN' is not an executable or a name on PATH." >&2
    exit 1
fi

_PY_VER=$("$PYTHON_BIN" -c 'import sys; print("{}.{}.{}".format(*sys.version_info[:3]))')
_PY_MAJOR_MINOR=$("$PYTHON_BIN" -c 'import sys; print("{}.{}".format(*sys.version_info[:2]))')
case "$_PY_MAJOR_MINOR" in
    3.14) ;;
    *)
        echo "WARNING: $PYTHON_BIN reports Python $_PY_VER, not 3.14.x." >&2
        echo "Continuing -- pyproject.toml's requires-python still governs what pip accepts." >&2
        ;;
esac
echo "==> Using $PYTHON_BIN (Python $_PY_VER)"

# ── Create or reuse the venv ──
if [ -x "$VENV_DIR/bin/python" ]; then
    echo "==> Reusing existing venv at $VENV_DIR"
else
    echo "==> Creating venv at $VENV_DIR"
    "$PYTHON_BIN" -m venv "$VENV_DIR"
fi

VENV_PY="$VENV_DIR/bin/python"
VENV_PIP="$VENV_DIR/bin/pip"

echo "==> Upgrading pip/setuptools/wheel"
"$VENV_PY" -m pip install --upgrade pip setuptools wheel -q

# ── Build the install target ──
if [ -n "$EXTRAS" ]; then
    _TARGET=".[$EXTRAS]"
else
    _TARGET="."
fi

_INSTALL_ARGS="install"
[ "$EDITABLE" = true ] && _INSTALL_ARGS="$_INSTALL_ARGS -e"

echo "==> Installing $_TARGET (editable=$EDITABLE) from $REPO_ROOT"
# shellcheck disable=SC2086
(cd "$REPO_ROOT" && "$VENV_PIP" $_INSTALL_ARGS "$_TARGET")

# ── Optional lock file ──
if [ "$DO_LOCK" = true ]; then
    _TAG=$("$VENV_PY" -c 'import sys; print("py{}{}".format(*sys.version_info[:2]))')
    _LOCK_DIR="$REPO_ROOT/requirements"
    mkdir -p "$_LOCK_DIR"
    _LOCK_FILE="$_LOCK_DIR/dev-${_TAG}.lock.txt"
    {
        echo "# Generated by scripts/dev_install.sh --lock on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
        echo "# python: $_PY_VER ($PYTHON_BIN), extras: ${EXTRAS:-<none>}"
        echo "# Reproduce with: pip install -r $(basename "$_LOCK_FILE")"
        echo "# This is a snapshot for reference, not a hash-pinned lock -- it is not"
        echo "# installed by dev_install.sh itself and pyproject.toml stays authoritative."
        "$VENV_PIP" freeze --exclude-editable
    } > "$_LOCK_FILE"
    echo "==> Wrote $_LOCK_FILE"
fi

echo ""
echo "==> Done. Activate with:"
echo "      . $VENV_DIR/bin/activate"
echo "    Then run tests with, e.g.:"
echo "      pytest tests/ -k 'not qlora and not saving'"
